export const ERROR_STATUS = {
  INVALID_ARGUMENT: 400,
  NOT_FOUND: 404,
  AMBIGUOUS_PLACE: 409,
  OUT_OF_CAMPUS: 422,
  ROUTE_UNAVAILABLE: 422,
  INSUFFICIENT_DATA: 503,
  UNAUTHORIZED: 401,
  FORBIDDEN: 403,
  CONFIRMATION_REQUIRED: 409,
  UNSUPPORTED_INTEGRATION: 503,
  SERVICE_UNAVAILABLE: 503,
  UPSTREAM_ERROR: 502,
  RATE_LIMITED: 429,
  TIMEOUT: 504,
  INTERNAL_ERROR: 500,
  MODEL_KEY_INVALID: 503,
  MODEL_NOT_FOUND_OR_FORBIDDEN: 503,
  MODEL_ENDPOINT_INVALID: 503,
  MODEL_NETWORK_ERROR: 502,
  MODEL_QUOTA_EXHAUSTED: 503,
  MODEL_RATE_LIMITED: 429,
  MODEL_TOOLS_UNSUPPORTED: 503,
  MODEL_JSON_UNSUPPORTED: 503,
  MODEL_SERVICE_UNAVAILABLE: 503,
  MODEL_TIMEOUT: 504,
  MODEL_TEST_REQUIRED: 503,
  MODEL_TEST_BUDGET_EXCEEDED: 429,
  MODEL_SELECTION_REQUIRED: 503,
  RUN_LIMIT_EXCEEDED: 429,
  CANCELLED: 499,
} as const;

export type ErrorCode = keyof typeof ERROR_STATUS;

export class ApiError extends Error {
  constructor(
    public readonly code: ErrorCode,
    message: string,
    public readonly retryable = false,
  ) {
    super(message);
    this.name = "ApiError";
  }
}
